/* —— 生成池（按比例分配 940 个名额） —— */
function _genOne(fam) {
  let name = '', cat = 'ornament', dy = '';
  if (fam === 'porcelain') {
    const p = _pick(PORCELAIN);
    dy = _pick(p.dy);
    const f = _pick(PORCELAIN_FORM);
    name = `${p.w}${_pick(PORCELAIN_MOTIF)}${f[0]}`;
    cat = f[1];
  } else if (fam === 'bronze') {
    dy = _pick(BRONZE_DY);
    const f = _pick(BRONZE_FORM);
    name = `${_pick(BRONZE_MOTIF)}${f[0]}`;
    cat = f[1];
  } else if (fam === 'jade') {
    dy = _pick(JADE_DY);
    const f = _pick(JADE_FORM);
    name = `${_pick(JADE_MAT)}${_pick(JADE_MOTIF)}${f[0]}`;
    cat = f[1];
  } else if (fam === 'jewel') {
    dy = _pick(JEWEL_DY);
    const f = _pick(JEWEL_FORM);
    name = `${_pick(JEWEL_MAT)}${_pick(['缠枝纹', '龙凤纹', '云纹', '宝相花纹', '花鸟纹'])}${f[0]}`;
    cat = f[1];
  } else if (fam === 'painting') {
    const m = _pick(PAINTERS);
    dy = m;
    name = `《${_pick(PAINT_TITLES)}》`;
    cat = 'painting';
  } else if (fam === 'calligraphy') {
    dy = _pick(CALLI_MASTERS);
    name = `${_pick(CALLI_STYLE)}${_pick(['诗文', '千字文', '兰亭诗', '自书诗', '论书语'])}${_pick(CALLI_FORM)}`;
    cat = 'scroll';
  } else if (fam === 'enamel') {
    dy = _pick(ENAMEL_DY);
    const f = _pick(ENAMEL_FORM);
    name = `${_pick(ENAMEL_KIND)}${_pick(ENAMEL_MOTIF)}${f[0]}`;
    cat = f[1];
  } else if (fam === 'clock') {
    dy = _pick(CLOCK_DY);
    name = `铜镀金${_pick(CLOCK_NAMES)}`;
    cat = 'clock';
  } else {
    dy = _pick(WOOD_DY);
    const f = _pick(WOOD_FORM);
    name = `${_pick(WOOD_KIND)}${_pick(['云龙纹', '山水楼阁纹', '花鸟纹', '福寿纹'])}${f[0]}`;
    cat = f[1];
  }
  /* 品质权重抽取（普通生成件几乎不会出传奇） */
  const roll = _rnd() * 100;
  let rv;
  if (roll < 0.4) rv = 5; else if (roll < 4) rv = 4; else if (roll < 14) rv = 3;
  else if (roll < 40) rv = 2; else rv = 1;
  return { name, dy, cat, rv };
}

const FAMILY_PLAN = [
  ['porcelain', 0.44], ['bronze', 0.13], ['jade', 0.14], ['jewel', 0.08],
  ['painting', 0.07], ['calligraphy', 0.04], ['enamel', 0.05], ['clock', 0.025], ['wood', 0.025],
];
const GENERATED = [];
{
  const counts = FAMILY_PLAN.map(([, p]) => Math.round(p * 940));
  counts[0] += 940 - counts.reduce((a, b) => a + b, 0);   /* 余数补给瓷器 */
  FAMILY_PLAN.forEach(([fam], i) => {
    for (let k = 0; k < counts[i]; k++) GENERATED.push(_genOne(fam));
  });
  /* 洗牌（固定种子），避免同类扎堆 */
  for (let i = GENERATED.length - 1; i > 0; i--) {
    const j = Math.floor(_rnd() * (i + 1));
    [GENERATED[i], GENERATED[j]] = [GENERATED[j], GENERATED[i]];
  }
}

