const RELICS = [];
CURATED.forEach(([name, dy, cat, rv, desc], i) => {
  RELICS.push({ id: 'r' + (i + 1), name, dy, cat, rv, desc, curated: true });
});
GENERATED.forEach((g, i) => {
  RELICS.push({ id: 'r' + (CURATED.length + i + 1), name: g.name, dy: g.dy, cat: g.cat, rv: g.rv, desc: '', curated: false });
});
const RELIC_MAP = Object.fromEntries(RELICS.map(r => [r.id, r]));

/* 路上刷新：按品质权重、且排除已拥有 */
function rollRelic(ownedSet) {
  const total = RARITY.slice(1).reduce((a, r) => a + r.weight, 0);
  let roll = Math.random() * total, rv = 1;
  for (let i = 1; i <= 5; i++) {
    if (roll < RARITY[i].weight) { rv = i; break; }
    roll -= RARITY[i].weight;
  }
  /* 在该品质的未拥有池中等概率抽一件；池空则向相邻品质找 */
  const tryPool = (v) => RELICS.filter(r => r.rv === v && !ownedSet.has(r.id));
  let pool = tryPool(rv);
  for (let d = 1; d <= 4 && !pool.length; d++) {
    if (rv + d <= 5) pool = tryPool(rv + d);
    if (!pool.length && rv - d >= 1) pool = tryPool(rv - d);
  }
  return pool.length ? pool[Math.floor(Math.random() * pool.length)] : null;
}

